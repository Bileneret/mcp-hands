"""MCP-Hands — локальный исполнительный слой (глаза + руки) для computer-use на Windows.

Пакет собирает наработки этапа 0 (спайк) в библиотеку. Правила, добытые замерами,
закодированы в модулях и не должны нарушаться вызывающим кодом:

  * `geometry` — единственный переводчик координат. UIA и Win32 дают координаты глазами
    процесса, DXGI — всегда физические пиксели, `SendInput` ждёт нормализованные 0..65535
    по виртуальному рабочему столу. Смешение пространств даёт систематический промах
    ровно на коэффициент масштаба DPI;
  * `screen` — захват с обязательным резервным путём: после сна дисплея DXGI отказывает
    и сам не восстанавливается;
  * `uia` — адресные запросы с кэш-реквестом и областью, выбранной по задаче;
  * `probe` — процесс-сателлит: зависший провайдер UIA не должен вешать агента;
  * `input` — активация окна и клик в два шага с проверкой позиции курсора;
  * `events` — ожидание событий вместо пауз, в выделенном потоке с циклом сообщений.
"""

