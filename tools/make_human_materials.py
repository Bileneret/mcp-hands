    write_task(
        "b08", "Файлы: разобрать папку загрузок по типам (удаление — только в корзину)",
        "1. Открыть папку `Загрузки` (в ней 5 файлов).\n"
        "2. Создать рядом папки: `документы`, `изображения`, `архивы`, `прочее`.\n"
        "3. Разложить файлы по категориям: отчёт — в документы, картинка — в изображения, "
        "архив — в архивы, заметки — в документы, временный файл — в прочее.\n"
        "4. Временный файл («мусор_времянка.tmp») отправить в КОРЗИНУ "
        "(через контекстное меню — «Удалить»).",
        "папка `Загрузки` пуста; временный файл отсутствует (в корзине); "
        "остальные файлы — по категориям.",
        ["Загрузки/ (5 файлов)"])
    write_task(
        "b09", "Excel/CSV: свести данные из файлов + построить график",
        "1. Открыть `данные_1.csv` и `данные_2.csv` (колонки «Месяц» и «Выручка»).\n"
        "2. Свести обе таблицы в один лист Excel: общий заголовок, затем четыре строки "
        "данных по месяцам.\n"
        "3. Построить столбчатую диаграмму по данным с заголовком "
        "«Выручка по месяцам».\n"
        "4. Сохранить как `сводная_выручка.xlsx`.",
        "файл `сводная_выручка.xlsx` существует: 4 строки данных и одна диаграмма.",
        ["данные_1.csv", "данные_2.csv"])
    write_task(
        "b10", "Комбо-витрина: «отчёт по лабе» — поиск → таблица → оформление → PDF",
        "1. Открыть `источники.html`, выписать четыре источника в `источники.csv` "
        "(как в b04).\n"
        "2. Открыть `статья.html`, вставить заголовок+ссылку и текст статьи в Word, "
        "оформить первый абзац стилем «Цитата», сохранить как `доклад.docx`.\n"
        "3. Экспортировать `доклад.docx` в `доклад.pdf`.",
        "существуют `источники.csv` (4 источника), `доклад.docx` (цитата+текст) "
        "и `доклад.pdf`.",
        ["источники.html", "статья.html"])

    # материалы
